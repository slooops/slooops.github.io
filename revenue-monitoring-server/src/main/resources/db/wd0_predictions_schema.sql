-- ----------------------------------------------------------------------------
-- WD0 Predictions (v2) - Schema definitions
-- ----------------------------------------------------------------------------
-- Owned & populated by the revenue-monitoring-server Spring application.
-- Run this once in ARFINRO before deploying the Wd0PredictiveService.
--
-- Replaces legacy ARFINRO.MIDCLOSE_PRIDECTION; the wd0-historical-data
-- dashboard now reads formal WD-3/-2/-1 rows from JSR_WD0_PREDICTIONS via
-- the WD0_VOLUMES_QUERY env var (PREDICTION_LOW IS NOT NULL filter).
--
-- Tables:
--   ARFINRO.JSR_WD0_PREDICTIONS    - final low/point/high predictions
--                                    (bounds NULL for daily training snapshots
--                                    outside the calibrated WD-3/-2/-1 range)
--   ARFINRO.JSR_WD0_RAW_SNAPSHOTS  - per-day raw counts (training data)
-- ----------------------------------------------------------------------------

CREATE TABLE ARFINRO.JSR_WD0_PREDICTIONS (
    PREDICTION_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PERIOD_NAME      VARCHAR2(10)   NOT NULL,            -- e.g. 'MAY-26'
    PERIOD_END_DATE  DATE           NOT NULL,            -- Saturday period_end
    PERIOD_TYPE      VARCHAR2(2)    NOT NULL,            -- 'ME' | 'QE' | 'YE'
    WD               VARCHAR2(6)    NOT NULL,            -- 'WD-1' .. 'WD-30'
    LINE_TYPE        VARCHAR2(10)   NOT NULL,            -- 'PRODUCT' | 'SERVICE'
    WEIGHTED_SUM     NUMBER         NOT NULL,            -- SUM(day_count * per_day_weight)
    PREDICTION_LOW   NUMBER,                             -- NULL when WD outside -3/-2/-1
    PREDICTION_HIGH  NUMBER,                             -- NULL when WD outside -3/-2/-1
    MODEL_VERSION    VARCHAR2(20)   NOT NULL,            -- e.g. 'v1-predecessor'
    GENERATED_AT     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT JSR_WD0_PRED_UQ
        UNIQUE (PERIOD_NAME, WD, LINE_TYPE, MODEL_VERSION, GENERATED_AT)
);

CREATE INDEX JSR_WD0_PRED_IDX_LATEST
    ON ARFINRO.JSR_WD0_PREDICTIONS (PERIOD_NAME, WD, LINE_TYPE, GENERATED_AT DESC);


-- One row per (count_date) per source query per run.
-- This is the audit trail AND the Stage 3 training matrix.
CREATE TABLE ARFINRO.JSR_WD0_RAW_SNAPSHOTS (
    SNAPSHOT_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PREDICTION_ID    NUMBER         NOT NULL,            -- FK to JSR_WD0_PREDICTIONS
    PERIOD_NAME      VARCHAR2(10)   NOT NULL,
    WD               VARCHAR2(6)    NOT NULL,
    LINE_TYPE        VARCHAR2(10)   NOT NULL,            -- 'PRODUCT' | 'SERVICE'
    SOURCE_QUERY     VARCHAR2(40)   NOT NULL,            -- 'PRODUCT_PROMISE_DATE'
                                                         -- 'SERVICE_FUTURE_INVOICE_RELEASE'
                                                         -- 'SERVICE_FLEXIBLE_INVOICE'
    COUNT_DATE       DATE           NOT NULL,            -- TRUNC date this row's count applies to
    DAY_OFFSET       NUMBER(2)      NOT NULL,            -- count_date - period_end (-3..+3)
    PER_DAY_WEIGHT   NUMBER(5,3)    NOT NULL,            -- weight applied to this day's count
    LINE_COUNT       NUMBER         NOT NULL,            -- raw count returned by query for that day
    GENERATED_AT     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT JSR_WD0_SNAP_FK
        FOREIGN KEY (PREDICTION_ID) REFERENCES ARFINRO.JSR_WD0_PREDICTIONS (PREDICTION_ID)
);

CREATE INDEX JSR_WD0_SNAP_IDX
    ON ARFINRO.JSR_WD0_RAW_SNAPSHOTS (PERIOD_NAME, WD, LINE_TYPE);

